    /// `[x, y]` or `{x, y}`; nil when absent.
    static func point(_ value: Any?) throws -> CGPoint? {
        guard let value else { return nil }
        if let pair = value as? [Any], pair.count == 2,
           let x = (pair[0] as? NSNumber)?.doubleValue, let y = (pair[1] as? NSNumber)?.doubleValue {
            return CGPoint(x: x, y: y)
        }
        if let dict = value as? [String: Any],
           let x = (dict["x"] as? NSNumber)?.doubleValue, let y = (dict["y"] as? NSNumber)?.doubleValue {
            return CGPoint(x: x, y: y)
        }
        throw ScriptError("A point is [x, y] or {x, y}")
    }

    /// Colours (evenly spaced) or `{offset, color}` objects, sorted by offset.
    static func gradientStops(_ value: Any?) throws -> [(offset: CGFloat, color: CGColor)] {
        guard let list = value as? [Any], list.count >= 2 else {
            throw ScriptError("stops needs at least two colours, like [\"#ff0000\", \"#0000ff\"] or [{offset: 0, color: \"red\"}, …]")
        }
        var stops: [(offset: CGFloat, color: CGColor)] = []
        for (n, entry) in list.enumerated() {
            let even = CGFloat(n) / CGFloat(list.count - 1)
            if let dict = entry as? [String: Any], let raw = dict["color"] ?? dict["colour"] {
                let offset = (dict["offset"] ?? dict["position"] ?? dict["at"]).flatMap { ($0 as? NSNumber)?.doubleValue }
                stops.append((min(max(CGFloat(offset ?? Double(even)), 0), 1), try ScriptGeometry.color(from: raw).cgColor))
            } else {
                stops.append((even, try ScriptGeometry.color(from: entry).cgColor))
            }
        }
        return stops.sorted { $0.offset < $1.offset }
    }

    /// The gradient drawn into a copy of the layer's pixels through Core
    /// Graphics, clipped to `coverage` (source space) when the selection
    /// has one. Mirrors `DocumentStore.pixelsGradiented`, with N stops.
    static func gradiented(_ layer: Layer, start: CGPoint, end: CGPoint, shape: GradientShape,
                           colors: [CGColor], locations: [CGFloat], coverage: MaskTexture?) -> CGImage? {
        let width = layer.source.width, height = layer.source.height
        guard width >= 1, height >= 1, layer.transform.isInvertible,
              let ctx = CGContext(data: nil, width: width, height: height,
                                  bitsPerComponent: 8, bytesPerRow: 0,
                                  space: DezzyColorSpace.displayP3,
                                  bitmapInfo: CGImageAlphaInfo.premultipliedLast.rawValue) else { return nil }
        ctx.draw(layer.source, in: layer.sourceRect)
        if let coverage, coverage.width == width, coverage.height == height, let mask = coverage.cgImage {
            ctx.clip(to: layer.sourceRect, mask: mask)
        }
        ctx.concatenate(layer.transform.inverted())
        let srgb = colors.map { $0.converted(to: DezzyColorSpace.sRGB, intent: .defaultIntent, options: nil) ?? $0 }
        guard let gradient = CGGradient(colorsSpace: DezzyColorSpace.sRGB, colors: srgb as CFArray,
                                        locations: locations) else { return nil }
        let options: CGGradientDrawingOptions = [.drawsBeforeStartLocation, .drawsAfterEndLocation]
        switch shape {
        case .linear:
            ctx.drawLinearGradient(gradient, start: start, end: end, options: options)
        case .radial:
            ctx.drawRadialGradient(gradient, startCenter: start, startRadius: 0, endCenter: start,
                                   endRadius: hypot(end.x - start.x, end.y - start.y), options: options)
        }
        return ctx.makeImage()
    }

    static func changeSummary(_ wd: WorkingDocument) -> String {
        var parts: [String] = []
        if wd.isNew {
            parts.append("created \(Int(wd.document.canvasSize.width))×\(Int(wd.document.canvasSize.height))")
        } else if wd.base.canvasSize != wd.document.canvasSize {
            parts.append("canvas \(Int(wd.base.canvasSize.width))×\(Int(wd.base.canvasSize.height)) → \(Int(wd.document.canvasSize.width))×\(Int(wd.document.canvasSize.height))")
        }
        let baseByID = Dictionary(wd.base.layers.map { ($0.id, $0) }, uniquingKeysWith: { a, _ in a })
        let newByID = Dictionary(wd.document.layers.map { ($0.id, $0) }, uniquingKeysWith: { a, _ in a })
        let added = wd.document.layers.filter { baseByID[$0.id] == nil }.map(\.name)
        let removed = wd.base.layers.filter { newByID[$0.id] == nil }.map(\.name)
        let changed = wd.document.layers.filter { layer in
            guard let old = baseByID[layer.id] else { return false }
            return old != layer
        }.map(\.name)
        if !added.isEmpty { parts.append("added \(nameList(added))") }
        if !removed.isEmpty { parts.append("removed \(nameList(removed))") }
        if !changed.isEmpty { parts.append("changed \(nameList(changed))") }
        if wd.base.layers.map(\.id) != wd.document.layers.map(\.id), added.isEmpty, removed.isEmpty {
            parts.append("reordered layers")
        }
        if wd.selection != wd.baseSelection { parts.append("selection changed") }
        if parts.isEmpty { parts.append("no visible change") }
        return parts.joined(separator: "; ")
    }

    /// Quoted names, or a count with the most common names once the list
    /// would drown the result ("108 layers: \"Rectangle\" ×108").
    static func nameList(_ names: [String]) -> String {
        if names.count <= 8 { return names.map { "\"\($0)\"" }.joined(separator: ", ") }
        var counts: [String: Int] = [:]
        for name in names { counts[name, default: 0] += 1 }
        let top = counts.sorted { $0.value != $1.value ? $0.value > $1.value : $0.key < $1.key }.prefix(3)
            .map { $0.value == 1 ? "\"\($0.key)\"" : "\"\($0.key)\" ×\($0.value)" }
        let more = counts.count > 3 ? ", …" : ""
        return "\(names.count) layers: \(top.joined(separator: ", "))\(more)"
    }
