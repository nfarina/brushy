import CoreGraphics
import Foundation

/// A script's transactional view of the open documents (§6 for what that
/// buys). Each document is copied in as a `Document` value; every operation
/// the script performs mutates the copy through the pure ops in `Model/`;
/// nothing reaches a `DocumentStore` until `ScriptRunner` commits the touched
/// copies — one history entry per document, or nothing at all if the script
/// threw. The session is also what a CLI or MCP front end would drive: it is
/// plain Swift over plain values, with JSON in and JSON out.
///
/// Thread-agnostic and main-thread-free: the runner constructs it on main,
/// hands it to the script thread, and reads it back on main afterwards.
final class ScriptSession {
    struct WorkingDocument {
        let id: String
        var title: String
        /// The value the copy started from; the runner refuses to commit over
        /// a store whose document has since moved (§6 — no silent clobbers).
        let base: Document
        var document: Document
        let baseSelection: SelectionState
        var selection: SelectionState
        let baseSelectedLayerIDs: [UUID]
        var selectedLayerIDs: [UUID]
        /// Created by the script (`dezzy.newDocument`); the runner opens a
        /// real window for it on commit.
        let isNew: Bool

        var ids: ScriptState.IDMap { ScriptState.IDMap(document) }

        var isTouched: Bool {
            isNew || document != base || selection != baseSelection
                || selectedLayerIDs != baseSelectedLayerIDs
        }
    }

    private(set) var documents: [WorkingDocument] = []
    private(set) var activeID: String?
    /// Images a script can place: generated by a tool, loaded from disk, or
    /// rendered from a layer. Keyed by the id the script holds.
    private(set) var images: [String: CGImage] = [:]
    private var nextImageNumber = 1
    /// Hands out the id a new document will have in the registry, so the
    /// script can refer to it before it exists.
    private let reserveDocumentID: () -> String

    init(documents: [WorkingDocument], activeID: String?, reserveDocumentID: @escaping () -> String) {
        self.documents = documents
        self.activeID = activeID ?? documents.first?.id
        self.reserveDocumentID = reserveDocumentID
    }

    static func working(id: String, title: String, document: Document,
                        selection: SelectionState = .empty,
                        selectedLayerIDs: [UUID] = []) -> WorkingDocument {
        WorkingDocument(id: id, title: title, base: document, document: document,
                        baseSelection: selection, selection: selection,
                        baseSelectedLayerIDs: selectedLayerIDs, selectedLayerIDs: selectedLayerIDs,
                        isNew: false)
    }

    func registerImage(_ image: CGImage, id: String? = nil) -> String {
        let key = id ?? "img\(nextImageNumber)"
        nextImageNumber += 1
        images[key] = image
        return key
    }

    var touchedDocuments: [WorkingDocument] { documents.filter(\.isTouched) }

    // MARK: - Dispatch

    /// Performs one operation. `op` names it; the rest are its arguments.
    /// Returns a JSON-compatible value.
    func perform(_ args: [String: Any]) throws -> Any {
        let result = try dispatch(args)
        try checkLayerBudget()
        return result
    }

    /// The most layers one script may add to a document. A model that hits
    /// this is almost always faking something a single layer can do (a
    /// gradient out of a hundred one-pixel strips); the error says so.
    static let maxAddedLayersPerScript = 200

    private func checkLayerBudget() throws {
        for wd in documents {
            let added = wd.document.layers.count - (wd.isNew ? 0 : wd.base.layers.count)
            if added > Self.maxAddedLayersPerScript {
                throw ScriptError("This script has added more than \(Self.maxAddedLayersPerScript) layers to \(wd.id). That usually means it is building something one layer can hold — use fill, fillGradient, addShape or addText on a single layer instead, or ask the user first.")
            }
        }
    }

    private func dispatch(_ args: [String: Any]) throws -> Any {
        guard let op = args["op"] as? String else { throw ScriptError("Missing op") }
        switch op {
        // Session
        case "documents": return documents.map(summary)
        case "activeDocument": return activeID ?? NSNull()
        case "newDocument": return try newDocument(args)
        case "loadImage": return try loadImage(args)
        // Document
        case "state": return try state(args)
        case "describe": return try describe(args)
        case "resizeCanvas": return try resizeCanvas(args)
        case "crop": return try crop(args)
        case "scaleImage": return try scaleImage(args)
        case "fitCanvasToContent": return try fitCanvasToContent(args)
        case "addTextLayer": return try addTextLayer(args)
        case "addShapeLayer": return try addShapeLayer(args)
        case "addLayer": return try addLayer(args)
        case "addImageLayer": return try addImageLayer(args)
        case "group": return try group(args)
        case "ungroup": return try ungroup(args)
        case "setGroup": return try setGroup(args)
        case "deleteGroup": return try deleteGroup(args)
        case "arrange": return try arrange(args)
        case "align": return try align(args)
        case "distribute": return try distribute(args)
        case "select": return try select(args)
        case "selectAll": return try selectAll(args)
        case "deselect": return try deselect(args)
        case "invertSelection": return try invertSelection(args)
        case "setSelectedLayers": return try setSelectedLayers(args)
        case "copyLayers": return try copyLayers(args)
        // Layer
        case "setLayer": return try setLayer(args)
        case "setFrame": return try setFrame(args)
        case "move": return try move(args)
        case "rotate": return try rotate(args)
        case "flip": return try flip(args)
        case "duplicate": return try duplicate(args)
        case "delete": return try delete(args)
        case "reorder": return try reorder(args)
        case "setText": return try setText(args)
        case "setShape": return try setShape(args)
        case "addMask": return try addMask(args)
        case "removeMask": return try removeMask(args)
        case "fill": return try fill(args)
        case "fillGradient": return try fillGradient(args)
        case "draw": return try draw(args)
        case "measureText":
            return ["width": ScriptDrawing.measureText(string(args, "text") ?? "",
                                                       font: string(args, "font") ?? "10px sans-serif")]
        default:
            throw ScriptError("Unknown operation \"\(op)\"")
        }
    }

    // MARK: - Argument helpers

    private func index(of docID: String) throws -> Int {
        guard let i = documents.firstIndex(where: { $0.id == docID }) else {
            throw ScriptError("No open document \"\(docID)\"; use dezzy.documents to list them")
        }
        return i
    }

    private func docIndex(_ args: [String: Any]) throws -> Int {
        guard let id = args["doc"] as? String else { throw ScriptError("Missing document") }
        return try index(of: id)
    }

    private func number(_ args: [String: Any], _ key: String) -> CGFloat? {
        guard let n = args[key] as? NSNumber else { return nil }
        let v = CGFloat(n.doubleValue)
        return v.isFinite ? v : nil
    }

    private func required(_ args: [String: Any], _ key: String) throws -> CGFloat {
        guard let v = number(args, key) else { throw ScriptError("Missing or non-numeric \"\(key)\"") }
        return v
    }

    private func string(_ args: [String: Any], _ key: String) -> String? {
        args[key] as? String
    }

    private func bool(_ args: [String: Any], _ key: String) -> Bool? {
        (args[key] as? NSNumber)?.boolValue
    }

    /// Resolves a layer reference: a short id, else an exact name, else a
    /// case-insensitive name. Topmost wins among duplicate names.
    private func layerID(_ ref: Any?, in wd: WorkingDocument) throws -> UUID {
        guard let ref = ref as? String, !ref.isEmpty else { throw ScriptError("Missing layer") }
        let ids = wd.ids
        if let id = ids.layers[ref] { return id }
        if let layer = wd.document.layers.last(where: { $0.name == ref }) { return layer.id }
        if let layer = wd.document.layers.last(where: { $0.name.lowercased() == ref.lowercased() }) {
            return layer.id
        }
        throw ScriptError("No layer \"\(ref)\" in \(wd.id); layer ids and names are in dezzy.doc(\"\(wd.id)\").layers")
    }

    private func layerIDs(_ refs: Any?, in wd: WorkingDocument) throws -> [UUID] {
        guard let refs = refs as? [Any] else { throw ScriptError("Expected an array of layers") }
        return try refs.map { try layerID($0, in: wd) }
    }

    private func groupID(_ ref: Any?, in wd: WorkingDocument) throws -> UUID {
        guard let ref = ref as? String, !ref.isEmpty else { throw ScriptError("Missing group") }
        if let id = wd.ids.groups[ref] { return id }
        if let group = wd.document.groups.last(where: { $0.name == ref }) { return group.id }
        throw ScriptError("No group \"\(ref)\" in \(wd.id)")
    }

    private func layer(_ id: UUID, in wd: WorkingDocument) throws -> Layer {
        guard let layer = wd.document[layerID: id] else { throw ScriptError("Layer no longer exists") }
        return layer
    }

    private func mutate(_ i: Int, _ body: (inout Document) throws -> Void) rethrows {
        try body(&documents[i].document)
    }

    private func replace(_ layer: Layer, in i: Int) {
        documents[i].document = documents[i].document.replacingLayer(layer)
    }

    private func topLeftRect(_ args: [String: Any], in wd: WorkingDocument) throws -> CGRect {
        CGRect(x: try required(args, "x"), y: try required(args, "y"),
               width: try required(args, "width"), height: try required(args, "height"))
    }

    private func canvasRect(_ args: [String: Any], in wd: WorkingDocument) throws -> CGRect {
        ScriptGeometry.canvas(try topLeftRect(args, in: wd), canvasHeight: wd.document.canvasSize.height)
    }

    private static let ok: [String: Any] = ["ok": true]

    // MARK: - Session ops

    private func summary(_ wd: WorkingDocument) -> [String: Any] {
        ["id": wd.id, "title": wd.title,
         "width": Int(wd.document.canvasSize.width), "height": Int(wd.document.canvasSize.height),
         "layerCount": wd.document.layers.count, "active": wd.id == activeID]
    }

    private func newDocument(_ args: [String: Any]) throws -> Any {
        let size = Document.clampedCanvasSize(CGSize(width: try required(args, "width"),
                                                     height: try required(args, "height")))
        let id = reserveDocumentID()
        let title = string(args, "name") ?? "Untitled"
        let doc = Document(canvasSize: size)
        documents.append(WorkingDocument(id: id, title: title, base: doc, document: doc,
                                         baseSelection: .empty, selection: .empty,
                                         baseSelectedLayerIDs: [], selectedLayerIDs: [],
                                         isNew: true))
        return ["id": id]
    }

    private func loadImage(_ args: [String: Any]) throws -> Any {
        guard let path = string(args, "path"), !path.isEmpty else { throw ScriptError("Missing path") }
        let url = URL(fileURLWithPath: (path as NSString).expandingTildeInPath)
        let image: CGImage
        do {
            image = try ImageImporter.importImage(at: url)
        } catch {
            throw ScriptError("Could not load \(url.path): \(error.localizedDescription)")
        }
        let id = registerImage(image)
        return ["image": id, "width": image.width, "height": image.height]
    }

    // MARK: - Document ops

    private func state(_ args: [String: Any]) throws -> Any {
        let wd = documents[try docIndex(args)]
        return ScriptState.document(id: wd.id, title: wd.title, document: wd.document,
                                    selection: wd.selection, selectedLayerIDs: wd.selectedLayerIDs,
                                    ids: wd.ids)
    }

    private func describe(_ args: [String: Any]) throws -> Any {
        let wd = documents[try docIndex(args)]
        return Self.describe(wd)
    }

    static func describe(_ wd: WorkingDocument) -> String {
        ScriptState.describe(id: wd.id, title: wd.title, document: wd.document,
                             selection: wd.selection, selectedLayerIDs: wd.selectedLayerIDs,
                             ids: wd.ids)
    }

    private func resizeCanvas(_ args: [String: Any]) throws -> Any {
        let i = try docIndex(args)
        let current = documents[i].document.canvasSize
        let size = Document.clampedCanvasSize(CGSize(width: number(args, "width") ?? current.width,
                                                     height: number(args, "height") ?? current.height))
        let anchor = try ScriptGeometry.anchor(named: string(args, "anchor") ?? "center")
        let before = documents[i].document
        documents[i].document = before.resizingCanvas(to: size, anchor: anchor)
        shiftSelection(i, from: before)
        return Self.ok
    }

    private func crop(_ args: [String: Any]) throws -> Any {
        let i = try docIndex(args)
        let rect = try canvasRect(args, in: documents[i]).standardized.integral
        guard rect.width >= 1, rect.height >= 1 else { throw ScriptError("Crop rect must be at least 1×1") }
        let before = documents[i].document
        documents[i].document = before.cropped(to: rect)
        shiftSelection(i, from: before)
        return Self.ok
    }

    /// Crop-shaped ops move the canvas origin; the selection rides along.
    private func shiftSelection(_ i: Int, from before: Document) {
        guard !documents[i].selection.isEmpty else { return }
        // Recover the shift from the first layer's transform (crop only
        // translates), else from the size change assuming a top-left anchor.
        let shift: CGPoint
        if let old = before.layers.first, let new = documents[i].document.layers.first {
            shift = CGPoint(x: new.transform.tx - old.transform.tx, y: new.transform.ty - old.transform.ty)
        } else {
            shift = .zero
        }
        documents[i].selection = documents[i].selection
            .transformed(by: CGAffineTransform(translationX: shift.x, y: shift.y))
    }

    private func scaleImage(_ args: [String: Any]) throws -> Any {
        let i = try docIndex(args)
        let current = documents[i].document.canvasSize
        var width = number(args, "width")
        var height = number(args, "height")
        guard width != nil || height != nil else { throw ScriptError("Give a width, a height, or both") }
        if width == nil { width = current.width * (height! / current.height) }
        if height == nil { height = current.height * (width! / current.width) }
        let size = Document.clampedCanvasSize(CGSize(width: width!, height: height!))
        documents[i].document = documents[i].document.scaled(to: size)
        documents[i].selection = .empty
        return Self.ok
    }

    private func fitCanvasToContent(_ args: [String: Any]) throws -> Any {
        let i = try docIndex(args)
        let before = documents[i].document
        documents[i].document = before.fittingCanvasToContent(padding: number(args, "padding") ?? 0)
        shiftSelection(i, from: before)
        return Self.ok
    }

    private func insert(_ layer: Layer, into i: Int, args: [String: Any]) throws -> Any {
        let above = try args["above"].map { try layerID($0, in: documents[i]) }
        documents[i].document = documents[i].document.insertingLayer(layer, above: above)
        documents[i].selectedLayerIDs = [layer.id]
        return ["id": documents[i].ids.short(layer.id)]
    }

    private func addTextLayer(_ args: [String: Any]) throws -> Any {
        let i = try docIndex(args)
        var spec = TextSpec()
        spec.text = string(args, "text") ?? ""
        guard !spec.text.isEmpty else { throw ScriptError("Text layers need text") }
        if let font = string(args, "fontName") { spec.fontName = font }
        if let size = number(args, "fontSize") { spec.fontSize = Double(size) }
        if let color = args["color"] { spec.color = try ScriptGeometry.color(from: color) }
        guard let image = VectorRasterizer.render(text: spec) else {
            throw ScriptError("Could not render the text")
        }
        let height = documents[i].document.canvasSize.height
        let topLeft = ScriptGeometry.canvas(CGPoint(x: number(args, "x") ?? 0, y: number(args, "y") ?? 0),
                                            canvasHeight: height)
        let transform = CGAffineTransform(translationX: topLeft.x.rounded(),
                                          y: (topLeft.y - CGFloat(image.height)).rounded())
        let layer = Layer(name: string(args, "name") ?? Self.layerName(forText: spec.text),
                          source: image, transform: transform, kind: .text(spec))
        return try insert(layer, into: i, args: args)
    }

    static func layerName(forText text: String) -> String {
        let firstLine = text.split(separator: "\n").first.map(String.init) ?? "Text"
        return firstLine.count > 24 ? String(firstLine.prefix(24)) + "…" : firstLine
    }

    private func shapeStyle(_ args: [String: Any], base: ShapeSpec = ShapeSpec()) throws -> ShapeSpec {
        var spec = base
        if let kind = string(args, "kind") {
            guard let k = ShapeSpec.Kind(rawValue: kind) else {
                throw ScriptError("Unknown shape kind \"\(kind)\"; use rectangle, ellipse or line")
            }
            spec.kind = k
        }
        if args.keys.contains("fill") {
            spec.fill = args["fill"] is NSNull ? nil : try ScriptGeometry.color(from: args["fill"]!)
            if spec.fill?.a == 0 { spec.fill = nil }
        }
        if args.keys.contains("stroke") {
            spec.stroke = args["stroke"] is NSNull ? nil : try ScriptGeometry.color(from: args["stroke"]!)
            if spec.stroke?.a == 0 { spec.stroke = nil }
        }
        if let width = number(args, "strokeWidth") { spec.strokeWidth = Double(max(0, width)) }
        if let style = string(args, "strokeStyle") {
            guard let s = ShapeSpec.StrokeStyle(rawValue: style) else {
                throw ScriptError("Unknown stroke style \"\(style)\"; use solid, dashed or dotted")
            }
            spec.strokeStyle = s
        }
        if let a = bool(args, "arrowStart") { spec.arrowStart = a }
        if let a = bool(args, "arrowEnd") { spec.arrowEnd = a }
        return spec
    }

    private func addShapeLayer(_ args: [String: Any]) throws -> Any {
        let i = try docIndex(args)
        let height = documents[i].document.canvasSize.height
        let style = try shapeStyle(args)
        let spec: ShapeSpec
        let origin: CGPoint
        if style.kind == .line {
            let from = ScriptGeometry.canvas(CGPoint(x: try required(args, "x1"), y: try required(args, "y1")),
                                             canvasHeight: height)
            let to = ScriptGeometry.canvas(CGPoint(x: try required(args, "x2"), y: try required(args, "y2")),
                                           canvasHeight: height)
            (spec, origin) = VectorRasterizer.shapeSpec(from: .zero, lineFrom: from, lineTo: to, style: style)
        } else {
            let rect = try canvasRect(args, in: documents[i])
            (spec, origin) = VectorRasterizer.shapeSpec(from: rect, lineFrom: nil, lineTo: nil, style: style)
        }
        guard let image = VectorRasterizer.render(shape: spec) else {
            throw ScriptError("Could not render the shape")
        }
        let layer = Layer(name: string(args, "name") ?? spec.kind.displayName, source: image,
                          transform: CGAffineTransform(translationX: origin.x.rounded(), y: origin.y.rounded()),
                          kind: .shape(spec))
        return try insert(layer, into: i, args: args)
    }

    /// A paint layer: transparent and canvas-sized by default, or a solid
    /// colour block at the given frame.
    private func addLayer(_ args: [String: Any]) throws -> Any {
        let i = try docIndex(args)
        let canvas = documents[i].document.canvasSize
        let color = try args["color"].map { try ScriptGeometry.color(from: $0) }
        let hasFrame = args["width"] != nil || args["height"] != nil || args["x"] != nil || args["y"] != nil
        let name = string(args, "name") ?? "Layer \(documents[i].document.layers.filter(\.isPaintable).count + 1)"
        if color == nil, !hasFrame {
            guard let layer = DocumentStore.blankPaintLayer(canvasSize: canvas, name: name) else {
                throw ScriptError("Could not create the layer")
            }
            return try insert(layer, into: i, args: args)
        }
        let frame = CGRect(x: number(args, "x") ?? 0, y: number(args, "y") ?? 0,
                           width: number(args, "width") ?? canvas.width,
                           height: number(args, "height") ?? canvas.height).standardized
        guard frame.width >= 1, frame.height >= 1 else { throw ScriptError("Layer size must be at least 1×1") }
        guard let image = Self.solidImage(width: Int(frame.width.rounded()), height: Int(frame.height.rounded()),
                                          color: color ?? ColorSpec(r: 0, g: 0, b: 0, a: 0)) else {
            throw ScriptError("Could not create the layer")
        }
        let canvasFrame = ScriptGeometry.canvas(frame, canvasHeight: canvas.height)
        let layer = Layer(name: name, source: image,
                          transform: CGAffineTransform(translationX: canvasFrame.minX.rounded(),
                                                       y: canvasFrame.minY.rounded()),
                          isPaintable: true)
        return try insert(layer, into: i, args: args)
    }

    static func solidImage(width: Int, height: Int, color: ColorSpec) -> CGImage? {
        guard width >= 1, height >= 1,
              let ctx = CGContext(data: nil, width: width, height: height,
                                  bitsPerComponent: 8, bytesPerRow: 0,
                                  space: DezzyColorSpace.displayP3,
                                  bitmapInfo: CGImageAlphaInfo.premultipliedLast.rawValue) else { return nil }
        if color.a > 0 {
            ctx.setFillColor(color.cgColor)
            ctx.fill(CGRect(x: 0, y: 0, width: width, height: height))
        }
        return ctx.makeImage()
    }

    /// Places a registered image. Default placement mirrors File ▸ Place:
    /// centred, scaled down to fit the canvas. `x`/`y` pin the top-left;
    /// `width`/`height` fit the image inside that box (aspect kept) unless
    /// `stretch` is true.
    private func addImageLayer(_ args: [String: Any]) throws -> Any {
        let i = try docIndex(args)
        guard let ref = string(args, "image") else { throw ScriptError("Missing image") }
        guard let image = images[ref] else {
            throw ScriptError("No image \"\(ref)\"; images come from dezzy.loadImage(path) or the generate tool")
        }
        let canvas = documents[i].document.canvasSize
        let name = string(args, "name") ?? ref
        var layer = DocumentStore.placedLayer(image, named: name, canvasSize: canvas)
        let x = number(args, "x"), y = number(args, "y")
        let w = number(args, "width"), h = number(args, "height")
        if x != nil || y != nil || w != nil || h != nil {
            let current = ScriptGeometry.topLeft(layer.canvasBounds, canvasHeight: canvas.height)
            var size = CGSize(width: image.width, height: image.height)
            if w != nil || h != nil {
                if bool(args, "stretch") == true, let w, let h {
                    size = CGSize(width: w, height: h)
                } else {
                    let box = CGSize(width: w ?? .greatestFiniteMagnitude, height: h ?? .greatestFiniteMagnitude)
                    let scale = min(box.width / size.width, box.height / size.height)
                    size = CGSize(width: size.width * scale, height: size.height * scale)
                }
            }
            let frame = CGRect(x: x ?? current.minX, y: y ?? current.minY,
                               width: size.width, height: size.height)
            layer.transform = ScriptGeometry.transform(fitting: layer.sourceSize,
                                                       to: ScriptGeometry.canvas(frame, canvasHeight: canvas.height))
        }
        return try insert(layer, into: i, args: args)
    }

    private func group(_ args: [String: Any]) throws -> Any {
        let i = try docIndex(args)
        let ids = try layerIDs(args["layers"], in: documents[i])
        guard !ids.isEmpty else { throw ScriptError("Group needs at least one layer") }
        let name = string(args, "name") ?? documents[i].document.nextGroupName()
        guard let (doc, groupID) = documents[i].document.addingGroup(named: name, aroundLayers: ids) else {
            throw ScriptError("Could not group those layers")
        }
        documents[i].document = doc
        return ["id": documents[i].ids.short(groupID)]
    }

    private func ungroup(_ args: [String: Any]) throws -> Any {
        let i = try docIndex(args)
        let id = try groupID(args["group"], in: documents[i])
        documents[i].document = documents[i].document.ungrouping(id)
        return Self.ok
    }

    private func setGroup(_ args: [String: Any]) throws -> Any {
        let i = try docIndex(args)
        let id = try groupID(args["group"], in: documents[i])
        guard let index = documents[i].document.groupIndex(of: id) else { throw ScriptError("Group no longer exists") }
        var group = documents[i].document.groups[index]
        if let name = string(args, "name") { group.name = name }
        if let visible = bool(args, "visible") { group.isVisible = visible }
        if let opacity = number(args, "opacity") { group.opacity = Float(min(max(opacity, 0), 1)) }
        if args.keys.contains("blendMode") {
            if let mode = string(args, "blendMode"), mode != "pass-through" {
                group.blendMode = try ScriptGeometry.blendMode(named: mode)
            } else {
                group.blendMode = nil
            }
        }
        documents[i].document.groups[index] = group
        return Self.ok
    }

    private func deleteGroup(_ args: [String: Any]) throws -> Any {
        let i = try docIndex(args)
        let id = try groupID(args["group"], in: documents[i])
        documents[i].document = documents[i].document.removingGroup(id)
        pruneSelectedLayers(i)
        return Self.ok
    }

    private func pruneSelectedLayers(_ i: Int) {
        let live = Set(documents[i].document.layers.map(\.id))
        documents[i].selectedLayerIDs.removeAll { !live.contains($0) }
    }

    private func arrange(_ args: [String: Any]) throws -> Any {
        let i = try docIndex(args)
        let ids = try layerIDs(args["layers"], in: documents[i])
        let direction = ArrangeDirection(rawValue: string(args, "direction") ?? "horizontal")
        guard let direction else { throw ScriptError("direction must be \"horizontal\" or \"vertical\"") }
        let alignment: ArrangeAlignment
        switch (string(args, "align") ?? "start").lowercased() {
        case "start", "top", "left": alignment = .start
        case "center", "centre", "middle": alignment = .center
        case "end", "bottom", "right": alignment = .end
        default: throw ScriptError("align must be start, center or end (top/bottom, left/right also work)")
        }
        let height = documents[i].document.canvasSize.height
        var origin: CGPoint?
