    private func duplicate(_ args: [String: Any]) throws -> Any {
        let i = try docIndex(args)
        let id = try layerID(args["layer"], in: documents[i])
        let original = try layer(id, in: documents[i])
        let copy = original.duplicated(name: string(args, "name") ?? original.name + " copy")
