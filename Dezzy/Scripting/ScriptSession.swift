    /// Copies layers into another document, on top of its stack. Canvas
    /// positions are kept unless `x`/`y` place the copies' union top-left.
    private func copyLayers(_ args: [String: Any]) throws -> Any {
        let from = try docIndex(args)
        guard let toID = string(args, "to") else { throw ScriptError("Missing destination document") }
        let to = try index(of: toID)
        let ids = try layerIDs(args["layers"], in: documents[from])
        let sourceHeight = documents[from].document.canvasSize.height
        let targetHeight = documents[to].document.canvasSize.height
        var copies: [Layer] = []
        var union = CGRect.null
        for id in ids {
            let original = try layer(id, in: documents[from])
            var copy = original.duplicated(name: original.name)
            copy.groupID = nil
            copy.isClippedToBelow = false
            // Keep the top-left position across differently sized canvases.
            let tl = ScriptGeometry.topLeft(original.canvasBounds, canvasHeight: sourceHeight)
            let target = ScriptGeometry.canvas(tl, canvasHeight: targetHeight)
            copy.transform = original.transform.concatenating(
                CGAffineTransform(translationX: target.minX - original.canvasBounds.minX,
                                  y: target.minY - original.canvasBounds.minY))
            union = union.union(copy.canvasBounds)
            copies.append(copy)
        }
        if let x = number(args, "x"), let y = number(args, "y"), !union.isNull {
            let wanted = ScriptGeometry.canvas(CGPoint(x: x, y: y), canvasHeight: targetHeight)
            let delta = CGPoint(x: wanted.x - union.minX, y: wanted.y - union.maxY)
            for k in copies.indices {
                copies[k].transform = copies[k].transform.concatenating(
                    CGAffineTransform(translationX: delta.x, y: delta.y))
            }
        }
        for copy in copies {
            documents[to].document = documents[to].document.insertingLayer(copy, above: nil)
        }
        documents[to].selectedLayerIDs = copies.map(\.id)
        let ids2 = documents[to].ids
        return copies.map { ids2.short($0.id) }
    }

