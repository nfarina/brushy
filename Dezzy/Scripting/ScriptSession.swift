    /// Source pixels with `color` composited where `coverage` says (whole
    /// image when nil). Coverage is source-resolution, row 0 at top, like
    /// every mask buffer (§5b).
    static func filled(_ source: CGImage, color: ColorSpec, coverage: MaskTexture?) -> CGImage? {
        let width = source.width, height = source.height
        guard width >= 1, height >= 1,
              let ctx = CGContext(data: nil, width: width, height: height,
                                  bitsPerComponent: 8, bytesPerRow: 0,
                                  space: DezzyColorSpace.displayP3,
                                  bitmapInfo: CGImageAlphaInfo.premultipliedLast.rawValue) else { return nil }
        ctx.draw(source, in: CGRect(x: 0, y: 0, width: width, height: height))
        guard let coverage else {
            ctx.setBlendMode(.copy)
            ctx.setFillColor(color.cgColor)
            ctx.fill(CGRect(x: 0, y: 0, width: width, height: height))
            return ctx.makeImage()
        }
        // The fill colour in the layer's own (Display P3) space, premultiplied.
        let p3 = color.cgColor.converted(to: DezzyColorSpace.displayP3, intent: .defaultIntent, options: nil)
        let c = p3?.components ?? [0, 0, 0, 1]
        let fr = Double(c.count > 2 ? c[0] : 0), fg = Double(c.count > 2 ? c[1] : 0)
        let fb = Double(c.count > 2 ? c[2] : 0), fa = Double(c.count > 3 ? c[3] : 1)
        guard let data = ctx.data else { return nil }
        let rowBytes = ctx.bytesPerRow
        let bytes = data.assumingMemoryBound(to: UInt8.self)
        coverage.data.withUnsafeBytes { (raw: UnsafeRawBufferPointer) in
            guard let mask = raw.baseAddress?.assumingMemoryBound(to: UInt8.self),
                  coverage.width == width, coverage.height == height else { return }
            for row in 0..<height {
                // CGContext rows here are also top-first (bitmap origin is
                // the first byte), matching the mask's row order.
                let ctxRow = row
                for col in 0..<width {
                    let k = Double(mask[row * width + col]) / 255
                    guard k > 0 else { continue }
                    let p = ctxRow * rowBytes + col * 4
                    let old = (Double(bytes[p]) / 255, Double(bytes[p + 1]) / 255,
                               Double(bytes[p + 2]) / 255, Double(bytes[p + 3]) / 255)
                    // Selected pixels take the colour (with its own alpha)
                    // at coverage strength: k=1 replaces, k<1 blends.
                    let nr = fr * fa * k + old.0 * (1 - k)
                    let ng = fg * fa * k + old.1 * (1 - k)
                    let nb = fb * fa * k + old.2 * (1 - k)
                    let na = fa * k + old.3 * (1 - k)
                    bytes[p] = UInt8(min(max(nr * 255, 0), 255).rounded())
                    bytes[p + 1] = UInt8(min(max(ng * 255, 0), 255).rounded())
                    bytes[p + 2] = UInt8(min(max(nb * 255, 0), 255).rounded())
                    bytes[p + 3] = UInt8(min(max(na * 255, 0), 255).rounded())
                }
            }
        }
        return ctx.makeImage()
    }

