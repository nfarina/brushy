    /// Position-only changes translate (rotation and flips survive); a size
    /// change rebuilds the transform axis-aligned.
    private func setFrame(_ args: [String: Any]) throws -> Any {
        let i = try docIndex(args)
        var layer = try layer(try layerID(args["layer"], in: documents[i]), in: documents[i])
        let height = documents[i].document.canvasSize.height
        let current = ScriptGeometry.topLeft(layer.canvasBounds, canvasHeight: height)
        let width = number(args, "width"), h = number(args, "height")
        let frame = CGRect(x: number(args, "x") ?? current.minX, y: number(args, "y") ?? current.minY,
                           width: width ?? current.width, height: h ?? current.height)
        guard frame.width > 0, frame.height > 0 else { throw ScriptError("Frame size must be positive") }
        let canvasFrame = ScriptGeometry.canvas(frame, canvasHeight: height)
        if width == nil, h == nil {
            let delta = CGPoint(x: canvasFrame.minX - layer.canvasBounds.minX,
                                y: canvasFrame.minY - layer.canvasBounds.minY)
            layer.transform = TransformMath.moved(initial: layer.transform, delta: delta)
        } else {
            layer.transform = ScriptGeometry.transform(fitting: layer.sourceSize, to: canvasFrame)
        }
        replace(layer, in: i)
        return Self.ok
    }

