    /// `to`: "front", "back", "up", "down", or a 0-based index from the
    /// bottom; or `above`/`below` naming another layer. The moved layer
    /// adopts its new neighbour's group.
    private func reorder(_ args: [String: Any]) throws -> Any {
        let i = try docIndex(args)
        let id = try layerID(args["layer"], in: documents[i])
        var doc = documents[i].document
        guard let from = doc.layerIndex(of: id) else { throw ScriptError("Layer no longer exists") }
        var layer = doc.layers.remove(at: from)
        var at: Int
        var neighbourGroup: UUID?
        if let above = args["above"] {
            let anchor = try layerID(above, in: documents[i])
            guard let idx = doc.layerIndex(of: anchor) else { throw ScriptError("Layer no longer exists") }
            at = idx + 1
            neighbourGroup = doc.layers[idx].groupID
        } else if let below = args["below"] {
            let anchor = try layerID(below, in: documents[i])
            guard let idx = doc.layerIndex(of: anchor) else { throw ScriptError("Layer no longer exists") }
            at = idx
            neighbourGroup = doc.layers[idx].groupID
        } else if let n = args["to"] as? NSNumber, !(args["to"] is String) {
            at = min(max(n.intValue, 0), doc.layers.count)
            let neighbour = at < doc.layers.count ? doc.layers[at] : doc.layers.last
            neighbourGroup = neighbour?.groupID
        } else {
            switch (string(args, "to") ?? "").lowercased() {
            case "front", "top": at = doc.layers.count; neighbourGroup = nil
            case "back", "bottom": at = 0; neighbourGroup = nil
            case "up", "forward":
                at = min(from + 1, doc.layers.count)
                neighbourGroup = at > 0 ? doc.layers[at - 1].groupID : nil
            case "down", "backward":
                at = max(from - 1, 0)
                neighbourGroup = at < doc.layers.count ? doc.layers[at].groupID : nil
            default:
                throw ScriptError("to must be front, back, up, down or an index; or use above/below")
            }
        }
        layer.groupID = neighbourGroup
        doc.layers.insert(layer, at: at)
        documents[i].document = doc.normalizingGroups().normalizingClipping()
        return Self.ok
    }

    /// Re-rasterises a text layer from an updated spec, keeping its top-left
    /// (mirrors `DocumentStore.updateVectorLayer`).
    private func setText(_ args: [String: Any]) throws -> Any {
        let i = try docIndex(args)
        let layer = try layer(try layerID(args["layer"], in: documents[i]), in: documents[i])
        guard var spec = layer.kind.textSpec else { throw ScriptError("\"\(layer.name)\" is not a text layer") }
        if let text = string(args, "text") { spec.text = text }
        if let font = string(args, "fontName") { spec.fontName = font }
        if let size = number(args, "fontSize") { spec.fontSize = Double(size) }
        if let color = args["color"] { spec.color = try ScriptGeometry.color(from: color) }
        guard let image = VectorRasterizer.render(text: spec) else { throw ScriptError("Could not render the text") }
        let shift = CGAffineTransform(translationX: 0, y: CGFloat(layer.source.height - image.height))
        replace(Self.rerasterized(layer, image: image, kind: .text(spec), anchorShift: shift), in: i)
        return Self.ok
    }

    /// Re-rasterises a shape layer, keeping its centre.
    private func setShape(_ args: [String: Any]) throws -> Any {
        let i = try docIndex(args)
        let layer = try layer(try layerID(args["layer"], in: documents[i]), in: documents[i])
        guard let current = layer.kind.shapeSpec else { throw ScriptError("\"\(layer.name)\" is not a shape layer") }
        var spec = try shapeStyle(args, base: current)
        if spec.kind == .line, current.kind != .line { throw ScriptError("Use a new line layer instead of changing a shape into a line") }
        if spec.kind != .line, current.kind == .line { throw ScriptError("A line can't become a rectangle or ellipse") }
        // Padding may change with the stroke; keep the drawn geometry's size.
        let inner = CGSize(width: current.size.width - 2 * current.padding,
                           height: current.size.height - 2 * current.padding)
        spec.size = CGSize(width: inner.width + 2 * spec.padding, height: inner.height + 2 * spec.padding)
        if spec.kind == .line {
            let d = CGFloat(spec.padding - current.padding)
            spec.lineStart = CGPoint(x: current.lineStart.x + d, y: current.lineStart.y + d)
            spec.lineEnd = CGPoint(x: current.lineEnd.x + d, y: current.lineEnd.y + d)
        }
        guard let image = VectorRasterizer.render(shape: spec) else { throw ScriptError("Could not render the shape") }
        let shift = CGAffineTransform(translationX: CGFloat(layer.source.width - image.width) / 2,
                                      y: CGFloat(layer.source.height - image.height) / 2)
        replace(Self.rerasterized(layer, image: image, kind: .shape(spec), anchorShift: shift), in: i)
        return Self.ok
    }

    private static func rerasterized(_ layer: Layer, image: CGImage, kind: LayerKind,
                                     anchorShift: CGAffineTransform) -> Layer {
        var out = Layer(id: layer.id, sourceID: UUID(), name: layer.name, source: image,
                        transform: anchorShift.concatenating(layer.transform),
                        opacity: layer.opacity, isVisible: layer.isVisible, mask: nil,
                        isPaintable: false, kind: kind, blendMode: layer.blendMode,
                        isClippedToBelow: layer.isClippedToBelow, groupID: layer.groupID,
                        effects: layer.effects)
        if let mask = layer.mask, mask.texture.width == image.width, mask.texture.height == image.height {
            out.mask = mask
        }
        return out
    }

