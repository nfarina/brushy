    /// What a script did to a document, for the model: canvas size changes
    /// and layers added / removed / changed by name.
    /// A multi-stop gradient over a paint layer's pixels — inside the
    /// selection if there is one. `from`/`to` are top-left canvas points
    /// (default: the layer's top centre → bottom centre); beyond them the
    /// end colours clamp, as the Gradient tool does. Stops are colours,
    /// optionally with an offset in 0…1; without offsets they space evenly.
    private func fillGradient(_ args: [String: Any]) throws -> Any {
        let i = try docIndex(args)
        let layer = try layer(try layerID(args["layer"], in: documents[i]), in: documents[i])
        guard layer.isPaintable else {
            throw ScriptError("\"\(layer.name)\" is an imported image and can't be painted; add a new layer and fill that instead")
        }
        let canvasHeight = documents[i].document.canvasSize.height
        let frame = ScriptGeometry.topLeft(layer.canvasBounds, canvasHeight: canvasHeight)
        let from = try Self.point(args["from"]) ?? CGPoint(x: frame.midX, y: frame.minY)
        let to = try Self.point(args["to"]) ?? CGPoint(x: frame.midX, y: frame.maxY)
        guard from != to else { throw ScriptError("Gradient start and end must differ") }
        let stops = try Self.gradientStops(args["stops"])
        let shape: GradientShape
        switch (string(args, "shape") ?? "linear").lowercased() {
        case "linear": shape = .linear
        case "radial": shape = .radial
        case let other: throw ScriptError("Unknown gradient shape \"\(other)\"; use \"linear\" or \"radial\"")
        }
        let coverage: MaskTexture? = documents[i].selection.isEmpty ? nil
            : MaskFactory.maskTexture(for: layer, selection: documents[i].selection, featherCanvasPx: 0)
        guard let image = Self.gradiented(layer,
                                          start: ScriptGeometry.canvas(from, canvasHeight: canvasHeight),
                                          end: ScriptGeometry.canvas(to, canvasHeight: canvasHeight),
                                          shape: shape, colors: stops.map(\.color), locations: stops.map(\.offset),
                                          coverage: coverage) else {
            throw ScriptError("Could not draw the gradient")
        }
        let out = Layer(id: layer.id, sourceID: UUID(), name: layer.name, source: image,
                        transform: layer.transform, opacity: layer.opacity, isVisible: layer.isVisible,
                        mask: layer.mask, isPaintable: true, kind: layer.kind, blendMode: layer.blendMode,
                        isClippedToBelow: layer.isClippedToBelow, groupID: layer.groupID, effects: layer.effects)
        replace(out, in: i)
        return Self.ok
    }

